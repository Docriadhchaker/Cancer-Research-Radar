// Helper lookup to normalize user cancer type queries
export function findMatchingCohort(queryCancerType: string): OncologyCohort | null {
  const normalized = queryCancerType.toLowerCase().trim();
  
  if (normalized.includes('color') || normalized.includes('colon') || normalized.includes('rectal') || normalized.includes('bowel') || normalized.includes('crc')) {
    return ONCOLOGY_DATABASE['colorectal cancer'];
  }
  if (normalized.includes('breast') || normalized.includes('mammary') || normalized.includes('tnbc') || normalized.includes('her2')) {
    return ONCOLOGY_DATABASE['breast cancer'];
  }
  if (normalized.includes('lung') || normalized.includes('nsclc') || normalized.includes('sclc') || normalized.includes('bronchial')) {
    return ONCOLOGY_DATABASE['lung cancer'];
  }
  if (normalized.includes('pancrea') || normalized.includes('pdac')) {
    return ONCOLOGY_DATABASE['pancreatic cancer'];
  }
  if (normalized.includes('melanoma') || normalized.includes('skin cancer')) {
    return ONCOLOGY_DATABASE['melanoma'];
  }

  // Fallback check keys
  for (const [key, cohort] of Object.entries(ONCOLOGY_DATABASE)) {
    if (key.includes(normalized) || normalized.includes(key)) {
      return cohort;
    }
  }

  return null;
}
